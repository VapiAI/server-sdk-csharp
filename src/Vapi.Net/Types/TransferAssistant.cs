using global::System.Text.Json;
using global::System.Text.Json.Serialization;
using OneOf;
using Vapi.Net.Core;

namespace Vapi.Net;

[Serializable]
public record TransferAssistant : IJsonOnDeserialized
{
    [JsonExtensionData]
    private readonly IDictionary<string, JsonElement> _extensionData =
        new Dictionary<string, JsonElement>();

    /// <summary>
    /// Optional name for the transfer assistant
    /// </summary>
    [JsonPropertyName("name")]
    public string? Name { get; set; }

    /// <summary>
    /// Model configuration for the transfer assistant
    /// </summary>
    [JsonPropertyName("model")]
    public required TransferAssistantModel Model { get; set; }

    /// <summary>
    /// These are the options for the transfer assistant's voice.
    /// </summary>
    [JsonPropertyName("voice")]
    public object? Voice { get; set; }

    /// <summary>
    /// These are the options for the transfer assistant's transcriber.
    /// </summary>
    [JsonPropertyName("transcriber")]
    public object? Transcriber { get; set; }

    /// <summary>
    /// This is the first message that the transfer assistant will say.
    /// This can also be a URL to a custom audio file.
    ///
    /// If unspecified, assistant will wait for user to speak and use the model to respond once they speak.
    /// </summary>
    [JsonPropertyName("firstMessage")]
    public string? FirstMessage { get; set; }

    /// <summary>
    /// This is the background sound in the transfer assistant call. Default for phone calls is 'office' and default for web calls is 'off'.
    /// Bundled sounds: 'office', 'white-noise', 'city', 'crowd' and 'farm'. GPT Live assistants don't play 'office'.
    /// You can also provide a custom sound by providing a URL to an audio file.
    /// </summary>
    [JsonPropertyName("backgroundSound")]
    public OneOf<TransferAssistantBackgroundSoundZero, string>? BackgroundSound { get; set; }

    /// <summary>
    /// This is the plan for when the transfer assistant should start talking.
    ///
    /// You should configure this if the transfer assistant needs different endpointing behavior than the base assistant.
    ///
    /// If this is not set, the transfer assistant will inherit the start speaking plan from the base assistant.
    /// </summary>
    [JsonPropertyName("startSpeakingPlan")]
    public StartSpeakingPlan? StartSpeakingPlan { get; set; }

    /// <summary>
    /// This is the mode for the first message. Default is 'assistant-speaks-first'.
    ///
    /// Use:
    /// - 'assistant-speaks-first' to have the assistant speak first.
    /// - 'assistant-waits-for-user' to have the assistant wait for the user to speak first.
    /// - 'assistant-speaks-first-with-model-generated-message' to have the assistant speak first with a message generated by the model based on the conversation state.
    ///
    /// @default 'assistant-speaks-first'
    /// </summary>
    [JsonPropertyName("firstMessageMode")]
    public TransferAssistantFirstMessageMode? FirstMessageMode { get; set; }

    /// <summary>
    /// This is the maximum duration in seconds for the transfer assistant conversation.
    /// After this time, the transfer will be cancelled automatically.
    /// @default 120
    /// </summary>
    [JsonPropertyName("maxDurationSeconds")]
    public double? MaxDurationSeconds { get; set; }

    /// <summary>
    /// This decides whether the transfer assistant runs the main assistant's hooks on the operator leg of a `warm-transfer-experimental` transfer. The operator is the "customer" there. When unset or `true`, the transfer assistant runs all of the main assistant's hooks, plus `hooks`. When `false`, it runs only `hooks`, plus the main assistant's `call.ending` hooks. An `endCall` in an inherited `customer.speech.timeout` hook ends the whole call when the operator is silent, so set this to `false` to stop that.
    /// </summary>
    [JsonPropertyName("assistantHooksInheritEnabled")]
    public bool? AssistantHooksInheritEnabled { get; set; }

    /// <summary>
    /// These are the hooks the transfer assistant runs on the operator leg of a `warm-transfer-experimental` transfer. The operator is the "customer" there, so `customer.speech.timeout` fires on operator silence. Whether the main assistant's other hooks also run on the operator leg depends on `assistantHooksInheritEnabled`. These hooks run after them. `call.ending` and `call.timeElapsed` are not allowed here. The main assistant's `call.ending` hooks are kept automatically. Time-elapsed hooks are not armed on the operator leg. An `endCall` tool in these hooks ends the whole call, not only the operator leg. A `tool` action must carry an inline `tool`, because `toolId` is not resolved for the transfer assistant.
    /// </summary>
    [JsonPropertyName("hooks")]
    public IEnumerable<
        OneOf<
            CallHookAssistantSpeechInterrupted,
            CallHookCustomerSpeechInterrupted,
            CallHookCustomerSpeechTimeout,
            CallHookModelResponseTimeout,
            CallHookTranscriberEndpointedSpeechLowConfidence
        >
    >? Hooks { get; set; }

    /// <summary>
    /// This enables filtering of noise and background speech while the user is talking.
    ///
    /// Features:
    /// - Smart denoising using Krisp
    /// - Fourier denoising
    ///
    /// Smart denoising can be combined with or used independently of Fourier denoising.
    ///
    /// Order of precedence:
    /// - Smart denoising
    /// - Fourier denoising
    /// </summary>
    [JsonPropertyName("backgroundSpeechDenoisingPlan")]
    public BackgroundSpeechDenoisingPlan? BackgroundSpeechDenoisingPlan { get; set; }

    /// <summary>
    /// This is the number of seconds of silence to wait before ending the call. Defaults to 30.
    ///
    /// @default 30
    /// </summary>
    [JsonPropertyName("silenceTimeoutSeconds")]
    public double? SilenceTimeoutSeconds { get; set; }

    [JsonIgnore]
    public ReadOnlyAdditionalProperties AdditionalProperties { get; private set; } = new();

    void IJsonOnDeserialized.OnDeserialized() =>
        AdditionalProperties.CopyFromExtensionData(_extensionData);

    /// <inheritdoc />
    public override string ToString()
    {
        return JsonUtils.Serialize(this);
    }
}
