using global::System.Text.Json;
using global::System.Text.Json.Serialization;
using Vapi.Net.Core;

namespace Vapi.Net;

[Serializable]
public record SimulationOnboardingCoverageGapDto : IJsonOnDeserialized
{
    [JsonExtensionData]
    private readonly IDictionary<string, JsonElement> _extensionData =
        new Dictionary<string, JsonElement>();

    /// <summary>
    /// Requirement the gap is for, e.g. `R4`.
    /// </summary>
    [JsonPropertyName("requirementId")]
    public required string RequirementId { get; set; }

    /// <summary>
    /// Why no simulation covers it. `failed` and `budget` gaps are regenerated by an edit with `retryFailed`.
    /// </summary>
    [JsonPropertyName("reason")]
    public required SimulationOnboardingCoverageGapDtoReason Reason { get; set; }

    /// <summary>
    /// A short explanation for the user.
    /// </summary>
    [JsonPropertyName("detail")]
    public string? Detail { get; set; }

    [JsonIgnore]
    public ReadOnlyAdditionalProperties AdditionalProperties { get; private set; } = new();

    void IJsonOnDeserialized.OnDeserialized() =>
        AdditionalProperties.CopyFromExtensionData(_extensionData);

    /// <inheritdoc />
    public override string ToString()
    {
        return JsonUtils.Serialize(this);
    }
}
